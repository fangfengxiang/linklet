local Crypto = require("linklet.crypto")

describe("Authentication crypto", function()
    it("compares complete strings and rejects malformed values", function()
        assert.is_true(Crypto.constant_time_compare("hello", "hello"))
        assert.is_true(Crypto.constant_time_compare("", ""))
        assert.is_false(Crypto.constant_time_compare("hello", "world"))
        assert.is_false(Crypto.constant_time_compare("hello", "hi"))
        assert.is_false(Crypto.constant_time_compare(nil, "hello"))
        assert.is_false(Crypto.constant_time_compare("hello", nil))
        assert.is_false(Crypto.constant_time_compare({}, {}))
    end)

    it("fails closed for malformed signature inputs or absent OpenResty crypto", function()
        assert.is_false(Crypto.verify_signature(nil, "str", "sig"))
        assert.is_false(Crypto.verify_signature("sk", nil, "sig"))
        assert.is_false(Crypto.verify_signature("sk", "str", nil))
        assert.is_false(Crypto.verify_signature("", "str", "sig"))
        assert.is_false(Crypto.verify_signature("sk", "", "sig"))
        assert.is_false(Crypto.verify_signature("sk", "str", ""))
        assert.is_false(Crypto.verify_signature("sk", "str", "sig"))
    end)
end)
